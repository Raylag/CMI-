import numpy as np

# Настройка вывода numpy для красивого отображения чисел
np.set_printoptions(precision=4, suppress=True)

# --- Задаем матрицы из задания ---

# Матрица 1
K1 = np.array([
    [1,    2,   -1],
    [2.3,  4,    4],
    [-2,   5.1,  1],
    [0,    0.8,  6]
])

# Матрица 2
K2 = np.array([
    [3, 2, 1],
    [4, 3, 1],
    [2, 0, 2],
    [2, 1, 1]
])

def solve_svd(K, matrix_name):
    """
    Функция для вычисления SVD, вывода результатов 
    и проверки на ортогональность.
    """
    print("=" * 50)
    print(f"Решение для матрицы {matrix_name}")
    print("=" * 50)
    
    # Выполняем сингулярное разложение
    # U - левые сингулярные векторы
    # S - сингулярные числа
    # Vt - транспонированная матрица правых сингулярных векторов
    U, S, Vt = np.linalg.svd(K)
    
    # Получаем матрицу V (транспонируем Vt)
    V = Vt.T
    
    # Выводим сингулярные числа (в примере они обозначены как lambda)
    print("\nСингулярные числа (lambda):")
    print(S)
    
    # Выводим матрицу U
    print("\nМатрица U:")
    print(U)
    
    # Выводим матрицу V
    print("\nМатрица V:")
    print(V)
    
    # --- Проверка на ортогональность ---
    # Для ортогональной матрицы A должно выполняться A^T * A = I
    U_ortho_check = np.dot(U.T, U)
    V_ortho_check = np.dot(V.T, V)
    
    # Создаем единичные матрицы нужных размеров для сравнения
    I_U = np.eye(U.shape[1])
    I_V = np.eye(V.shape[1])
    
    # Проверяем, равны ли полученные произведения единичным матрицам
    # np.allclose используется из-за погрешности вычислений с плавающей точкой
    is_U_ortho = np.allclose(U_ortho_check, I_U)
    is_V_ortho = np.allclose(V_ortho_check, I_V)
    
    print("\n--- Проверка на ортогональность ---")
    print(f"U^T * U =\n{np.round(U_ortho_check, 4)}")
    print(f"Является ли U ортогональной: {'Да' if is_U_ortho else 'Нет'}")
    
    print(f"\nV^T * V =\n{np.round(V_ortho_check, 4)}")
    print(f"Является ли V ортогональной: {'Да' if is_V_ortho else 'Нет'}\n")

# Запускаем решение для обеих матриц
solve_svd(K1, "K1 (Задание 1)")
solve_svd(K2, "K2 (Задание 2)")
